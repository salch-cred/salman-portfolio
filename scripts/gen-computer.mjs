// Draws the isometric desk computer as plain SVG paths, so it stays crisp at any zoom.
import { writeFileSync } from 'node:fs';

const C = Math.cos(Math.PI / 6), S = 0.5;
const iso = ([x, y, z]) => [(x - y) * C, (x + y) * S - z];
const f = (n) => +n.toFixed(2);

function roundPoly(pts, r) {
  const n = pts.length; let d = '';
  for (let i = 0; i < n; i++) {
    const p = pts[i], a = pts[(i + n - 1) % n], b = pts[(i + 1) % n];
    const la = Math.hypot(a[0] - p[0], a[1] - p[1]), lb = Math.hypot(b[0] - p[0], b[1] - p[1]);
    const ra = Math.min(r, la / 2), rb = Math.min(r, lb / 2);
    const s = [p[0] + ((a[0] - p[0]) / la) * ra, p[1] + ((a[1] - p[1]) / la) * ra];
    const e = [p[0] + ((b[0] - p[0]) / lb) * rb, p[1] + ((b[1] - p[1]) / lb) * rb];
    d += `${i ? 'L' : 'M'}${f(s[0])} ${f(s[1])}Q${f(p[0])} ${f(p[1])} ${f(e[0])} ${f(e[1])}`;
  }
  return d + 'Z';
}

const out = [];
let delay = 0;
const path = (d, cls, extra = '') => {
  out.push(`<path d="${d}" class="${cls}" pathLength="1" style="--d:${delay.toFixed(2)}" ${extra}/>`);
};
const quad = (pts, cls, r = 3) => path(roundPoly(pts.map(iso), r), cls);
const line = (a, b, cls = 'l2') => {
  const [p, q] = [iso(a), iso(b)];
  path(`M${f(p[0])} ${f(p[1])}L${f(q[0])} ${f(q[1])}`, cls);
};

// A box with its three visible faces.
function box(x0, x1, y0, y1, z0, z1, r = 4, cls = '') {
  quad([[x0, y1, z1], [x1, y1, z1], [x1, y1, z0], [x0, y1, z0]], `f-front ${cls}`, r);
  quad([[x1, y1, z1], [x1, y0, z1], [x1, y0, z0], [x1, y1, z0]], `f-side ${cls}`, r);
  quad([[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]], `f-top ${cls}`, r);
}
const front = (u0, u1, v0, v1, y, cls, r = 4) =>
  quad([[u0, y, v1], [u1, y, v1], [u1, y, v0], [u0, y, v0]], cls, r);

// Base tray
delay = 0;
box(-96, 262, -74, 278, 0, 10, 16, 'tray');
quad([[-82, -60, 10], [248, -60, 10], [248, 264, 10], [-82, 264, 10]], 'l2 nofill', 12);

// Keyboard
delay = 0.15;
const kx0 = -16, kx1 = 156, ky0 = 128, ky1 = 214;
box(kx0, kx1, ky0, ky1, 10, 19, 5, 'kb');
const cols = 14, rows = 5, g = 2.1;
const kw = (kx1 - kx0 - 10 - g * (cols - 1)) / cols, kh = (ky1 - ky0 - 10 - g * (rows - 1)) / rows;
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    delay = 0.25 + (r + c) * 0.018;
    let x0 = kx0 + 5 + c * (kw + g), x1 = x0 + kw;
    const y0 = ky0 + 5 + r * (kh + g), y1 = y0 + kh;
    if (r === 4 && c >= 4 && c <= 8) { // space bar
      if (c !== 4) continue;
      x1 = x0 + 5 * kw + 4 * g;
    }
    box(x0, x1, y0, y1, 19, 22.5, 1.6, 'key');
  }
}

// Tower
delay = 0.5;
const W = 168, D = 96, H = 206, Z0 = 10;
box(0, W, 0, D, Z0, H, 12, 'tower');

// Top handle
delay = 0.75;
quad([[34, 12, H], [W - 34, 12, H], [W - 34, 26, H], [34, 26, H]], 'l1 inset', 7);
quad([[39, 15, H], [W - 39, 15, H], [W - 39, 23, H], [39, 23, H]], 'l2 nofill', 4);

// Front bezel, screen, drive slot, grille
delay = 0.85;
front(8, W - 8, 54, H - 12, D, 'l2 nofill', 10);
front(18, W - 44, 84, H - 22, D, 'l1 inset', 9);
delay = 1;
front(25, W - 51, 92, H - 29, D, 'crt', 13);
for (let i = 0; i < 9; i++) line([26 + i * 3.1, D, 32], [26 + i * 3.1, D, 56]);
front(W - 88, W - 22, 40, 50, D, 'l1 inset', 4);
line([W - 82, D, 45], [W - 28, D, 45]);
front(W - 20, W - 17, 36, 39, D, 'led', 1);
line([8, D, 30], [8, D, 26]);

// Side vents and ports
delay = 1.05;
for (let i = 0; i < 16; i++) line([W, 8 + i * 2.5, 142], [W, 8 + i * 2.5, 188]);
quad([[W, 44, 44], [W, 18, 44], [W, 18, 18], [W, 44, 18]], 'l1 inset', 3);
quad([[W, 39, 40], [W, 23, 40], [W, 23, 33], [W, 39, 33]], 'l2 nofill', 1);
quad([[W, 39, 29], [W, 23, 29], [W, 23, 22], [W, 39, 22]], 'l2 nofill', 1);

// Coiled cable, keyboard to tower
delay = 1.15;
const a = [kx1 + 2, 175, 15], b = [W + 2, D + 6, 18];
let d = '';
const n = 170;
for (let i = 0; i <= n; i++) {
  const t = i / n, ph = t * Math.PI * 34;
  const ease = t < 0.5 ? 2 * t * t : 1 - 2 * (1 - t) * (1 - t);
  const x = a[0] + (b[0] - a[0]) * t + 15 * Math.sin(Math.PI * t);
  const y = a[1] + (b[1] - a[1]) * ease;
  const z = a[2] + (b[2] - a[2]) * t;
  const [sx, sy] = iso([x, y, z]);
  d += `${i ? 'L' : 'M'}${f(sx + Math.cos(ph) * 3.6)} ${f(sy + Math.sin(ph) * 3.6)}`;
}
path(d, 'l1 nofill');

// Screen centre for the camera zoom.
const screen = iso([(25 + W - 51) / 2, D, (92 + H - 29) / 2]);
const pad = 14, minX = (-96 - 278) * C - pad, maxX = (262 + 74) * C + pad, minY = iso([0, 0, H])[1] - 74, maxY = (262 + 278) * S + 10 + pad;
const vb = [minX, minY, maxX - minX, maxY - minY].map(f);

writeFileSync('components/computer-art.ts',
`// Generated by scripts/gen-computer.mjs. Do not edit by hand.
export const VIEWBOX = '${vb.join(' ')}';
export const SCREEN = { x: ${(((screen[0] - minX) / (maxX - minX)) * 100).toFixed(2)}, y: ${(((screen[1] - minY) / (maxY - minY)) * 100).toFixed(2)} };
export const ART = ${JSON.stringify(out.join(''))};
`);
